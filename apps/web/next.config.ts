import path from 'node:path';

import bundleAnalyzer from '@next/bundle-analyzer';
import type { NextConfig } from 'next';
import createNextIntlPlugin from 'next-intl/plugin';

import { analyzeBundle, buildTimeAppUrl, e2eBuild } from './lib/env.ts';
import { buildServiceWorker } from './lib/pwa/build-sw.ts';

const repoRoot = path.join(import.meta.dirname, '../..');

/** Every workspace package ships TypeScript source, so Next.js compiles them. */
const workspacePackages = [
  '@causedeck/adapters',
  '@causedeck/ai',
  '@causedeck/auth',
  '@causedeck/billing',
  '@causedeck/capture',
  '@causedeck/config',
  '@causedeck/core',
  '@causedeck/db',
  '@causedeck/drafting',
  '@causedeck/flags',
  '@causedeck/i18n',
  '@causedeck/intelligence',
  '@causedeck/notifications',
  '@causedeck/observability',
  '@causedeck/storage',
  '@causedeck/ui',
  '@causedeck/validators',
];

const appUrl = buildTimeAppUrl();

// Baseline headers for every response. The nonce CSP is per request (proxy.ts); Caddy adds HSTS.
const securityHeaders = [
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  { key: 'X-Frame-Options', value: 'DENY' },
  // The camera sheet (#52) and the voice recorder (#543) use getUserMedia on our own origin.
  {
    key: 'Permissions-Policy',
    value: 'camera=(self), microphone=(self), geolocation=(), payment=()',
  },
];

const nextConfig: NextConfig = {
  output: 'standalone',
  // The e2e build (#16) gets its own output folder so it never overwrites a production build.
  ...(e2eBuild() ? { distDir: '.next-e2e' } : {}),
  outputFileTracingRoot: repoRoot,
  turbopack: { root: repoRoot },
  transpilePackages: workspacePackages,
  // Stable in Next.js 16 (it was `experimental.typedRoutes` before).
  typedRoutes: true,
  poweredByHeader: false,
  reactStrictMode: true,
  // Node-only observability SDKs load from node_modules at runtime instead of being bundled.
  serverExternalPackages: [
    'pino',
    'pino-pretty',
    '@sentry/node',
    '@opentelemetry/sdk-node',
    '@opentelemetry/auto-instrumentations-node',
    // The roster import preview parses PDFs with pdfjs (adapters' layoutFromPdf), which loads its
    // worker module by a runtime path the server bundle breaks (#459).
    'pdfjs-dist',
    // The document pipeline (#45, `@causedeck/intelligence`, reached through core's capture domain)
    // loads a WASM renderer, a native image encoder and a DOCX reader on first use; none of them
    // belongs in a server bundle.
    'mupdf',
    'sharp',
    'mammoth',
    // Core's drafting domain (#768) renders DOCX and PDF with these and reads font files by path.
    'docx',
    'pdf-lib',
    '@pdf-lib/fontkit',
  ],
  images: { remotePatterns: [] },
  experimental: {
    // CSRF: Server Actions only accept requests whose Origin matches the app (spike §3).
    serverActions: { allowedOrigins: appUrl ? [appUrl.host] : [] },
    // e2e harness only (#16): a compiled build that keeps `NODE_ENV=development`.
    ...(e2eBuild() ? { allowDevelopmentBuild: true as const } : {}),
  },
  headers: () =>
    Promise.resolve([
      { source: '/:path*', headers: securityHeaders },
      // The worker must always revalidate so updates are found; its scope stays the default `/`
      // (no `Service-Worker-Allowed`).
      {
        source: '/sw.js',
        headers: [
          { key: 'Cache-Control', value: 'no-cache, no-store, must-revalidate' },
          { key: 'Content-Type', value: 'text/javascript; charset=utf-8' },
        ],
      },
    ]),
};

const withNextIntl = createNextIntlPlugin({
  requestConfig: './i18n/request.ts',
  experimental: {
    // ICU messages compile at build time, which keeps the ICU parser out of the client bundle. The
    // catalogs live in @causedeck/i18n: one merged file per locale, generated by `pnpm i18n:types`.
    messages: {
      format: 'json',
      path: '../../packages/i18n/src/generated/messages',
      locales: 'infer',
      precompile: true,
    },
  },
});
const withBundleAnalyzer = bundleAnalyzer({ enabled: analyzeBundle() });

// The PWA service worker (#50) is bundled to public/sw.js when the dev server or a build starts.
// Next.js passes the phase to a function config; `NEXT_PHASE` is not set while the config loads.
export default function config(phase: string): NextConfig {
  if (phase === 'phase-development-server' || phase === 'phase-production-build') {
    buildServiceWorker(import.meta.dirname, { minify: phase === 'phase-production-build' });
  }
  return withBundleAnalyzer(withNextIntl(nextConfig));
}
