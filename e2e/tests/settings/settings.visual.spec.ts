// Settings visual baselines (#284): every viewport × theme project (360/768/1280, light and dark)
// with the clock frozen: the profile (owner, and read-only for a clerk), the rename dialog open,
// the roles page (owner, and read-only for a clerk, #285), the privacy page (owner, and denied for a
// clerk, #286), the integrations page (owner, and denied for a clerk, #287), and (#288) the export, danger zone and notification preferences pages.
// #305: the export page with the flag on (empty, building, ready, failed), the deletion dialog, the
// danger zone and the shell banner during a cool-off, and the account danger section. Baselines live
// in e2e/__screenshots__ and are only ever generated by the e2e workflow's `update_snapshots`
// dispatch in the pinned Playwright image (see e2e/README.md); without one the test is skipped.
import { existsSync } from 'node:fs';

import type { Page, TestInfo } from '@playwright/test';

import type { AsUser } from '../../fixtures/auth.ts';
import { expect, test } from '../../fixtures/index.ts';
import { enableExport, insertExport, withSql, WORKSPACE_ID, userId } from '../lifecycle/helpers.ts';
import { shellReady } from '../shell/helpers.ts';

function skipWithoutBaseline(testInfo: TestInfo, name: string) {
  const baseline = testInfo.snapshotPath(name, { kind: 'screenshot' });
  test.skip(
    testInfo.config.updateSnapshots === 'none' && !existsSync(baseline),
    'no baseline yet: dispatch the e2e workflow with update_snapshots',
  );
}

async function open(page: Page, asUser: AsUser, path: string, role: 'owner' | 'clerk' = 'owner') {
  await asUser(role, { path });
  await expect(page.locator('main').getByRole('heading', { level: 1 })).toBeVisible();
  await shellReady(page);
}

interface Shot {
  name: string;
  /** `database` is the worker database, for state the e2e stack has no worker to produce. */
  setUp: (page: Page, asUser: AsUser, database: string) => Promise<void>;
}

/** A workspace deletion in its cool-off, with fixed dates so the shot is stable. */
function scheduleDeletion(database: string): Promise<void> {
  return withSql(database, async (sql) => {
    await sql`
      insert into deletion_job (workspace_id, kind, requested_by, status, cooloff_until,
                                erase_after, created_at)
      values (${WORKSPACE_ID}, 'workspace', ${userId('owner')}, 'pending_cooloff',
              '2026-03-15T00:00:00+05:30', '2026-03-15T00:00:00+05:30',
              '2026-03-01T00:00:00+05:30')`;
  });
}

const SHA = 'ab'.repeat(32);

/** The export page with the flag on and, optionally, one export of the owner's. */
async function exportShot(
  page: Page,
  asUser: AsUser,
  database: string,
  row?: Parameters<typeof insertExport>[1],
) {
  await enableExport(database);
  if (row) await insertExport(database, row);
  await open(page, asUser, 'settings/export');
}

