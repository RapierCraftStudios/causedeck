test.describe('settings visual baselines', () => {
  for (const shot of SHOTS) {
    test(shot.name, async ({ page, asUser, db }, testInfo) => {
      skipWithoutBaseline(testInfo, shot.name);
      await shot.setUp(page, asUser, db.name);
      await expect(page).toHaveScreenshot(shot.name, { animations: 'disabled', caret: 'hide' });
    });
  }
});
