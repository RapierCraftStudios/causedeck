// Shared helpers for tests that need tables beyond the committed schema.
import { Secret } from '@causedeck/config/env';
import { generateDrizzleJson, generateMigration } from 'drizzle-kit/api';
import { sql } from 'drizzle-orm';

import { createDb, type Database } from '../../client.ts';
import { runMigrations } from '../../migrate.ts';
import { createOwnerDb } from '../../owner.ts';
import * as schema from '../../schema/index.ts';
import { createScratchDatabase, testDatabaseUrls } from '../../testing/index.ts';

export interface ScratchDb {
  owner: string;
  app: string;
  appDb: Database;
  close: () => Promise<void>;
}

/** A migrated scratch database plus the DDL for `extra` (generated by drizzle-kit, as the owner). */
export async function scratchWithTables(
  name: string,
  extra: Record<string, unknown>,
): Promise<ScratchDb> {
  const scratch = await createScratchDatabase(testDatabaseUrls(), name);
  await runMigrations({ url: new Secret(scratch.owner) });
  const statements = await generateMigration(
    generateDrizzleJson(schema, undefined, undefined, 'snake_case'),
    generateDrizzleJson({ ...schema, ...extra }, undefined, undefined, 'snake_case'),
  );
  const owner = createOwnerDb(new Secret(scratch.owner));
  try {
    for (const statement of statements) await owner.execute(sql.raw(statement));
  } finally {
    await owner.$client.end();
  }
  const appDb = createDb({ url: new Secret(scratch.app), role: 'app', max: 2 });
  return {
    ...scratch,
    appDb,
    close: async () => {
      await appDb.$client.end();
      await scratch.drop();
    },
  };
}

/** The Postgres error code of a (possibly Drizzle-wrapped) query error. */
export function pgCode(error: unknown): string | undefined {
  let current: unknown = error;
  while (typeof current === 'object' && current !== null) {
    if ('code' in current && typeof current.code === 'string' && /^[0-9A-Z]{5}$/.test(current.code))
      return current.code;
    current = 'cause' in current ? current.cause : undefined;
  }
  return undefined;
}

/** Await `promise`, expecting it to reject, and return the rejection. */
export async function rejection(promise: Promise<unknown>): Promise<unknown> {
  try {
    await promise;
  } catch (error) {
    return error;
  }
  throw new Error('expected the promise to reject');
}
