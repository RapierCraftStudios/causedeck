// Reviewed-SQL rule (spike §4.3, docs/engineering/database.md): every migration starts with a
// review header, and destructive statements need an explicit `-- contract:approved` annotation.
export const REVIEW_MARKER = '-- Reviewed-by:';
export const UNREVIEWED = '<unreviewed>';
export const CONTRACT_APPROVED = '-- contract:approved';

const DESTRUCTIVE = /\bDROP\s+(TABLE|COLUMN)\b/i;

export interface LintIssue {
  file: string;
  line: number;
  message: string;
}

/** The header `db:generate` stamps onto a new migration; the reviewer replaces the placeholder. */
export function reviewHeader(tag: string): string {
  return [
    `-- Migration ${tag}: generated by drizzle-kit, hand-reviewed before commit.`,
    `${REVIEW_MARKER} ${UNREVIEWED}`,
    '',
  ].join('\n');
}

export function hasReviewHeader(sqlText: string): boolean {
  return sqlText.startsWith('--') && sqlText.includes(REVIEW_MARKER);
}

export function lintMigrationSql(file: string, sqlText: string): LintIssue[] {
  const issues: LintIssue[] = [];
  const lines = sqlText.split('\n');

  // The header is the leading block of comment lines.
  const header: string[] = [];
  for (const line of lines) {
    if (!line.startsWith('--') || line.startsWith('--> statement-breakpoint')) break;
    header.push(line);
  }
  const review = header.find((line) => line.startsWith(REVIEW_MARKER));
  const reviewer = review?.slice(REVIEW_MARKER.length).trim() ?? '';
  if (!review) {
    issues.push({ file, line: 1, message: `missing review header (\`${REVIEW_MARKER} <name>\`)` });
  } else if (reviewer === '' || reviewer === UNREVIEWED) {
    issues.push({ file, line: 1, message: 'migration has not been reviewed yet' });
  }

  // An annotation applies from where it appears until the end of the statement (`;` or a drizzle
  // breakpoint), so it may sit on the line(s) above the statement or on the statement itself.
  let approved = false;
  for (const [i, line] of lines.entries()) {
    if (line.includes(CONTRACT_APPROVED)) approved = true;
    const code = line.replace(/--.*$/, '');
    if (DESTRUCTIVE.test(code) && !approved) {
      issues.push({
        file,
        line: i + 1,
        message: `destructive statement without \`${CONTRACT_APPROVED}\` (expand/contract: drop only in a contract migration)`,
      });
    }
    if (code.trimEnd().endsWith(';') || line.includes('--> statement-breakpoint')) {
      approved = false;
    }
  }
  return issues;
}
