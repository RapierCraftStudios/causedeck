// `pnpm i18n:types`: merge `src/messages/<locale>/<namespace>.json` into one catalog per locale and
// derive the `Messages` type from English.
//
// Outputs (committed; `pnpm i18n:check` fails when they are stale):
// - `src/generated/messages/<locale>.json`: the merged catalog. The next-intl plugin precompiles
//   these (one file per locale), and `loadMessages` imports them.
// - `src/generated/messages.d.ts`: the `Messages` interface that types `t()` keys.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { isPlainObject, mergeNamespaces, NAMESPACES, type Catalog } from '../src/catalog';
import { LOCALES, type Locale } from '../src/locales';

export const PACKAGE_ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Namespace file contents by locale: `{ en: { common: {...}, nav: {...} } }`. */
export type Sources = Record<Locale, Record<string, Catalog>>;

export function readSources(root = PACKAGE_ROOT): Sources {
  const sources = {} as Sources;
  for (const locale of LOCALES) {
    const dir = path.join(root, 'src/messages', locale);
    const files: Record<string, Catalog> = {};
    for (const file of readdirSync(dir)
      .filter((name) => name.endsWith('.json'))
      .sort()) {
      files[path.basename(file, '.json')] = JSON.parse(
        readFileSync(path.join(dir, file), 'utf8'),
      ) as Catalog;
    }
    sources[locale] = files;
  }
  return sources;
}

/** Order namespace files as in `NAMESPACES` (unknown files last) so output is stable. */
function ordered(files: Record<string, Catalog>): Record<string, Catalog> {
  const known = NAMESPACES.filter((name) => name in files);
  const unknown = Object.keys(files)
    .filter((name) => !(NAMESPACES as readonly string[]).includes(name))
    .sort();
  return Object.fromEntries([...known, ...unknown].map((name) => [name, files[name] ?? {}]));
}

export function mergeLocale(files: Record<string, Catalog>): Catalog {
  return mergeNamespaces(ordered(files));
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

function typeOf(catalog: Catalog, depth: number): string {
  const pad = '  '.repeat(depth);
  const lines = Object.entries(catalog).map(([key, value]) => {
    const name = IDENTIFIER.test(key) ? key : JSON.stringify(key);
    if (!isPlainObject(value)) return `${pad}  ${name}: string;`;
    if (Object.keys(value).length === 0) return `${pad}  ${name}: Record<string, never>;`;
    return `${pad}  ${name}: ${typeOf(value, depth + 1)};`;
  });
  return `{\n${lines.join('\n')}\n${pad}}`;
}

export function messagesDts(en: Catalog): string {
  return [
    '// Generated by `pnpm i18n:types` from src/messages/en. Do not edit.',
    `export type Messages = ${typeOf(en, 0)};`,
    '',
  ].join('\n');
}

export function catalogJson(catalog: Catalog): string {
  return `${JSON.stringify(catalog, null, 2)}\n`;
}

/** Every generated file, keyed by its path relative to the package root. */
export function generate(sources: Sources): Record<string, string> {
  const out: Record<string, string> = {};
  for (const locale of LOCALES) {
    out[`src/generated/messages/${locale}.json`] = catalogJson(mergeLocale(sources[locale]));
  }
  out['src/generated/messages.d.ts'] = messagesDts(mergeLocale(sources.en));
  return out;
}

function main(): void {
  for (const [file, content] of Object.entries(generate(readSources()))) {
    const target = path.join(PACKAGE_ROOT, file);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, content);
    console.log(`wrote ${file}`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
