// The redaction evaluation (#892): person-name recall and over-redaction of judges, advocates and
// bodies over the labelled set, rendered as the committed report `EVALUATION.md`.
import { buildFixtures, type LabelledJudgment } from './fixtures.ts';
import { redactJudgment, REDACTION_VERSION } from './index.ts';

export interface EvaluationResult {
  judgments: number;
  personMentions: number;
  personsLeaked: number;
  recall: number;
  keepMentions: number;
  keepLost: number;
  overRedaction: number;
  sensitiveJudgments: number;
  sensitiveWithMaskedTitle: number;
  victimIdentifiersLeaked: number;
  failures: string[];
}

export const redactFixture = (f: LabelledJudgment) =>
  redactJudgment({ pages: f.pages.map((text, i) => ({ pageNo: i + 1, text })) });

export function evaluate(fixtures: readonly LabelledJudgment[] = buildFixtures()): EvaluationResult {
  const r: EvaluationResult = {
    judgments: fixtures.length,
    personMentions: 0,
    personsLeaked: 0,
    recall: 0,
    keepMentions: 0,
    keepLost: 0,
    overRedaction: 0,
    sensitiveJudgments: 0,
    sensitiveWithMaskedTitle: 0,
    victimIdentifiersLeaked: 0,
    failures: [],
  };
  for (const f of fixtures) {
    const out = redactFixture(f);
    const text = out.pages.map((p) => p.text).join('\n').toLowerCase();
    for (const p of f.persons) {
      r.personMentions += 1;
      if (text.includes(p.toLowerCase())) {
        r.personsLeaked += 1;
        r.failures.push(`${f.id}: person survived: ${p}`);
      }
    }
    for (const k of f.keep) {
      r.keepMentions += 1;
      if (!text.includes(k.toLowerCase())) {
        r.keepLost += 1;
        r.failures.push(`${f.id}: kept text was redacted: ${k}`);
      }
    }
    if (f.sensitive !== null) {
      r.sensitiveJudgments += 1;
      const title = (out.caseTitle ?? '').toLowerCase();
      if (out.titleMasked && out.sensitiveCategory === f.sensitive) r.sensitiveWithMaskedTitle += 1;
      else r.failures.push(`${f.id}: sensitive category ${f.sensitive} read as ${out.sensitiveCategory}`);
      for (const v of f.victimIdentifiers) {
        if (text.includes(v.toLowerCase()) || title.includes(v.toLowerCase())) {
          r.victimIdentifiersLeaked += 1;
          r.failures.push(`${f.id}: victim identifier survived: ${v}`);
        }
      }
    }
  }
  r.recall = r.personMentions === 0 ? 1 : 1 - r.personsLeaked / r.personMentions;
  r.overRedaction = r.keepMentions === 0 ? 0 : r.keepLost / r.keepMentions;
  return r;
}

const pct = (n: number): string => `${(n * 100).toFixed(2)}%`;

/** The text of `EVALUATION.md`. */
export function renderReport(r: EvaluationResult): string {
  return `# Redaction evaluation (REDACTION_VERSION ${REDACTION_VERSION})

Generated by \`eval.test.ts\` from \`fixtures.ts\`; the test fails when this file is out of date
(regenerate with \`UPDATE_REDACTION_REPORT=1\`).

**The labelled set is synthetic.** Real labelled fixtures (#119) are still being collected by hand, so
the 40 judgments here are built from templates over invented name pools (criminal appeals, civil
suits, bail petitions with relatives, and every sensitive category). Names appear in full, by first
name, by surname, in capitals, with initials, as witnesses and as relatives. The numbers below show
the rules hold on this set; they are not a measure on real judgments. Re-run this evaluation on the
#119 fixtures or on imported judgments (#890) before relying on the recall.

| Measure | Result | Target |
| --- | --- | --- |
| Judgments | ${r.judgments} | at least 30 |
| Person-name mentions | ${r.personMentions} | |
| Person mentions that survived | ${r.personsLeaked} | |
| Person-name recall | ${pct(r.recall)} | at least 98% |
| Judge, advocate and body mentions | ${r.keepMentions} | |
| Judge, advocate and body mentions redacted | ${r.keepLost} | |
| Over-redaction | ${pct(r.overRedaction)} | at most 2% |
| Sensitive judgments | ${r.sensitiveJudgments} | |
| Sensitive judgments with category read and title masked | ${r.sensitiveWithMaskedTitle} | all |
| Victim or minor identifiers that survived | ${r.victimIdentifiersLeaked} | 0 |
`;
}
