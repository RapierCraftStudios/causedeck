// Generates tokens/TOKENS.md from the token CSS. Output is deterministic (no dates, stable order).
//
//   pnpm --filter @causedeck/ui gen:tokens            write TOKENS.md
//   pnpm --filter @causedeck/ui gen:tokens --check    exit 1 if TOKENS.md is stale
//
// tokens/__tests__/tokens.test.ts runs the same comparison, so CI fails on a stale file.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';

import { evaluateContrast } from './check-contrast';
import {
  LEVELS,
  SEMANTIC_COLOR_ROLES,
  STAGES,
  TOKENS_DIR,
  loadThemes,
  type TokenMap,
} from './lib/parse-tokens';

export const TOKENS_MD = path.join(TOKENS_DIR, 'TOKENS.md');

