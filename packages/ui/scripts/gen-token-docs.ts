/** Normalise `oklch(0.50 0.10 235)` and `oklch(0.5 0.1 235)` to the same string. */
export function normaliseOklch(value: string): string {
  return value.replaceAll(/\d*\.?\d+/g, (n) => String(Number(n))).replaceAll(/\s+/g, ' ');
}

const row = (cells: string[]): string => `| ${cells.join(' | ')} |`;
const code = (s: string): string => `\`${s}\``;

function table(head: string[], rows: string[][]): string[] {
  return [row(head), row(head.map(() => '---')), ...rows.map(row)];
}

function themedTable(names: string[], light: TokenMap, dark: TokenMap): string[] {
  return table(
    ['Token', 'Light', 'Dark'],
    names.map((n) => [
      code(`--${n}`),
      code(light.get(`--${n}`) ?? ''),
      code(dark.get(`--${n}`) ?? ''),
    ]),
  );
}

function prefixed(map: TokenMap, prefix: string): string[] {
  return [...map.keys()].filter((k) => k.startsWith(prefix)).map((k) => k.slice(2));
}

function singleTable(names: string[], map: TokenMap): string[] {
  return table(
    ['Token', 'Value'],
    names.map((n) => [code(`--${n}`), code(map.get(`--${n}`) ?? '')]),
  );
}

export function renderRaw(): string {
  const { light, dark } = loadThemes();
  const tuned: string[][] = [];
  for (const [name, [specLight, specDark]] of Object.entries(SPEC_COLORS)) {
    for (const [theme, spec, map] of [
      ['light', specLight, light],
      ['dark', specDark, dark],
    ] as const) {
      const actual = map.get(`--${name}`) ?? '(missing)';
      if (normaliseOklch(actual) !== normaliseOklch(spec)) {
        tuned.push([code(`--${name}`), theme, code(spec), code(actual)]);
      }
    }
  }
  const added = SEMANTIC_COLOR_ROLES.filter((r) => !(r in SPEC_COLORS));
  const contrast = evaluateContrast({ light, dark });

  const lines = [
    '# CauseDeck design tokens',
    '',
    'Generated by `pnpm --filter @causedeck/ui gen:tokens` from `tokens/*.css`. Do not edit by hand;',
    'CI fails when this file is stale. Rationale lives in `docs/design/design-language.md`.',
    '',
    'Apps import `@causedeck/ui/tokens.css` once, then `@causedeck/config/tailwind/preset.css`.',
    'Dark mode: class `dark` on `<html>` (next-themes `attribute="class"`); both themes set',
    '`color-scheme`.',
    '',
    '## Semantic colour roles',
    '',
    ...themedTable([...SEMANTIC_COLOR_ROLES], light, dark),
    '',
    '### Tuned for contrast',
    '',
    'Values that differ from the issue #7 starting values, changed only to pass the contrast gates.',
    '',
    ...(tuned.length > 0 ? table(['Token', 'Theme', 'Specified', 'Shipped'], tuned) : ['None.']),
    '',
    '### Added roles',
    '',
    ...added.map((r) =>
      r === 'line-control'
        ? `- ${code(`--${r}`)}: boundary of form controls (inputs, checkboxes) at >= 3:1 against surfaces. \`--line\` and \`--line-strong\` stay decorative hairlines.`
        : `- ${code(`--${r}`)}`,
    ),
    '',
    '## Proceeding stages',
    '',
    'Equal lightness within a theme, separated by hue. Always shown with the stage name.',
    '',
    ...themedTable(
      STAGES.flatMap((s) => [`stage-${s}`, `stage-${s}-soft`]),
      light,
      dark,
    ),
    '',
    '## Automation levels',
    '',
    'L1 neutral, L2 amber-leaning, L3 indigo, L4 brass. Always shown with the level label.',
    '',
    ...themedTable(
      LEVELS.map((l) => `level-${l}`),
      light,
      dark,
    ),
    '',
    '## Chart palette',
    '',
    'Every pair stays >= 12 CIEDE2000 apart under protanopia, deuteranopia and tritanopia',
    'simulation, and each series is >= 3:1 against `--surface-raised`.',
    '',
    ...themedTable(
      Array.from({ length: 8 }, (_, i) => `chart-${String(i + 1)}`),
      light,
      dark,
    ),
    '',
    '## Contrast',
    '',
    'WCAG 2.x ratio (the gate) and APCA Lc (reference). body: >= 4.5:1, AAA 7:1 target;',
    'text: >= 4.5:1; ui and large: >= 3:1.',
    '',
    ...table(
      ['Theme', 'Kind', 'Foreground', 'Background', 'WCAG', 'APCA Lc', 'Result'],
      contrast.map((r) => [
        r.theme,
        r.kind,
        code(`--${r.fg}`),
        code(`--${r.bg}`),
        `${r.ratio.toFixed(2)}:1`,
        String(r.apca),
        r.status,
      ]),
    ),
    '',
    '## Typography',
    '',
    ...singleTable(
      [
        ...prefixed(light, '--font-'),
        ...prefixed(light, '--text-'),
        ...prefixed(light, '--tracking-'),
        ...prefixed(light, '--weight-'),
        ...prefixed(light, '--leading-'),
        ...prefixed(light, '--measure-'),
      ],
      light,
    ),
    '',
    '## Spacing',
    '',
    ...singleTable(prefixed(light, '--space-'), light),
    '',
    '## Radius',
    '',
    ...singleTable(prefixed(light, '--radius-'), light),
    '',
    '## Elevation',
    '',
    ...themedTable(prefixed(light, '--shadow-'), light, dark),
    '',
    '## Motion',
    '',
    'Under `prefers-reduced-motion: reduce` every duration becomes `0.01ms` and',
    '`--motion-transform` becomes `none`.',
    '',
    ...singleTable([...prefixed(light, '--dur-'), ...prefixed(light, '--ease-')], light),
    '',
    '## Stacking',
    '',
    ...singleTable(prefixed(light, '--z-'), light),
    '',
    '## Other',
    '',
    ...singleTable(['hit', 'print-margin', 'motion-transform'], light),
    '',
  ];
  return lines.map((l) => l.replaceAll(/\s+/g, ' ').trimEnd()).join('\n');
}

/** The generated markdown, formatted with the repository Prettier config so `format:check` passes. */
export async function render(): Promise<string> {
  const options = (await resolveConfig(TOKENS_MD)) ?? {};
  return format(renderRaw(), { ...options, filepath: TOKENS_MD });
}

async function main(): Promise<void> {
  const next = await render();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(TOKENS_MD, 'utf8');
    } catch {
      // Missing file counts as stale.
    }
    if (current !== next) {
      console.error('tokens/TOKENS.md is stale. Run `pnpm --filter @causedeck/ui gen:tokens`.');
      process.exit(1);
    }
    console.log('tokens/TOKENS.md is up to date.');
    return;
  }
  writeFileSync(TOKENS_MD, next);
  console.log(`wrote ${path.relative(process.cwd(), TOKENS_MD)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
